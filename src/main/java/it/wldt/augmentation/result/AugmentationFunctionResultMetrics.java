package it.wldt.augmentation.result;

import it.wldt.exception.AugmentationFunctionException;

/**
 * Class representing the metrics of an augmentation function result. This class encapsulates various performance and
 * execution metrics related to the execution of an augmentation function, such as total execution time, start and end
 * timestamps, number of records processed and generated, and identifiers for the execution and node. These metrics can
 * be used for monitoring, debugging, and optimizing the performance of augmentation functions within the system.
 */
public class AugmentationFunctionResultMetrics {

    /**
     * The total execution time of the augmentation function, represented in milliseconds. This metric indicates the
     * overall time taken for the execution of the augmentation function, providing insights into the performance and
     * efficiency of the function within the system.
     */
    private Long totalExecutionTimeMs;

    /**
     * The start timestamp of the augmentation function execution, represented as a long value (milliseconds since epoch).
     * This metric indicates the exact time when the execution of the augmentation function began, allowing for better
     * tracking and analysis of the execution timeline.
     */
    private Long startTimestamp;

    /**
     * The end timestamp of the augmentation function execution, represented as a long value (milliseconds since epoch).
     * This metric indicates the exact time when the execution of the augmentation function completed, allowing for better
     * tracking and analysis of the execution timeline and performance of the function within the system.
     */
    private Long endTimestamp;

    /**
     * The number of records processed by the augmentation function during its execution.
     */
    private Integer recordsProcessed;

    /**
     * The number of records generated by the augmentation function as a result of its execution.
     */
    private Integer recordsGenerated;

    /**
     * The unique identifier for the execution of the augmentation function, allowing for better tracking and association
     * of metrics with specific executions within the system.
     */
    private String executionId;

    /**
     * The unique identifier for the node on which the augmentation function was executed, allowing for better tracking and
     * association of metrics with specific nodes within the system, which can be useful for monitoring and optimizing
     * the performance of augmentation functions across different nodes in a distributed environment.
     */
    private String nodeId;

    /**
     * Constructor for the AugmentationFunctionResultMetrics class, initializing the total execution time metric.
     * @param totalExecutionTimeMs The total execution time of the augmentation function, represented in milliseconds.
     * @throws AugmentationFunctionException if the total execution time is null or negative, indicating an invalid metric
     * value that cannot be used for performance analysis and monitoring of the augmentation function within the system.
     */
    public AugmentationFunctionResultMetrics(Long totalExecutionTimeMs) throws AugmentationFunctionException {
        if (totalExecutionTimeMs == null || totalExecutionTimeMs < 0) {
            throw new AugmentationFunctionException("Total execution time cannot be null or negative.");
        }
        this.totalExecutionTimeMs = totalExecutionTimeMs;
    }

    /**
     * Constructor for the AugmentationFunctionResultMetrics class, initializing the start and end timestamps, and calculating the total execution time.
     * @param startTimestamp The start timestamp of the augmentation function execution, represented as a long value (milliseconds since epoch).
     * @param endTimestamp The end timestamp of the augmentation function execution, represented as a long value (milliseconds since epoch).
     * @throws AugmentationFunctionException if either the start timestamp or end timestamp is null, or if the end timestamp
     * is earlier than the start timestamp, indicating invalid metric values that cannot be used for performance analysis
     * and monitoring of the augmentation function within the system.
     */
    public AugmentationFunctionResultMetrics(Long startTimestamp, Long endTimestamp) throws AugmentationFunctionException {
        if (startTimestamp == null || endTimestamp == null) {
            throw new AugmentationFunctionException("Start time and end time cannot be null.");
        }
        if (endTimestamp < startTimestamp) {
            throw new AugmentationFunctionException("End time cannot be earlier than start time.");
        }
        this.startTimestamp = startTimestamp;
        this.endTimestamp = endTimestamp;
        this.totalExecutionTimeMs = endTimestamp - startTimestamp;
    }

    /**
     * Gets the total execution time of the augmentation function, represented in milliseconds.
     * @return The total execution time of the augmentation function, represented in milliseconds.
     */
    public Long getTotalExecutionTimeMs() {
        return totalExecutionTimeMs;
    }

    /**
     * Sets the total execution time of the augmentation function, represented in milliseconds.
     * @param totalExecutionTimeMs The total execution time of the augmentation function, represented in milliseconds.
     */
    public void setTotalExecutionTimeMs(Long totalExecutionTimeMs) {
        this.totalExecutionTimeMs = totalExecutionTimeMs;
    }

    /**
     * Gets the start timestamp of the augmentation function execution, represented as a long value (milliseconds since epoch).
     * @return The start timestamp of the augmentation function execution, represented as a long value (milliseconds since epoch).
     */
    public Long getStartTimestamp() {
        return startTimestamp;
    }

    /**
     * Sets the start timestamp of the augmentation function execution, represented as a long value (milliseconds since epoch).
     * @param startTimestamp The start timestamp of the augmentation function execution, represented as a long value (milliseconds since epoch).
     */
    public void setStartTimestamp(Long startTimestamp) {
        this.startTimestamp = startTimestamp;
    }

    /**
     * Gets the end timestamp of the augmentation function execution, represented as a long value (milliseconds since epoch).
     * @return The end timestamp of the augmentation function execution, represented as a long value (milliseconds since epoch).
     */
    public Long getEndTimestamp() {
        return endTimestamp;
    }

    /**
     * Sets the end timestamp of the augmentation function execution, represented as a long value (milliseconds since epoch).
     * @param endTimestamp The end timestamp of the augmentation function execution, represented as a long value (milliseconds since epoch).
     */
    public void setEndTimestamp(Long endTimestamp) {
        this.endTimestamp = endTimestamp;
    }

    /**
     * Gets the number of records processed by the augmentation function during its execution.
     * @return The number of records processed by the augmentation function during its execution.
     */
    public Integer getRecordsProcessed() {
        return recordsProcessed;
    }

    /**
     * Sets the number of records processed by the augmentation function during its execution.
     * @param recordsProcessed The number of records processed by the augmentation function during its execution.
     */
    public void setRecordsProcessed(Integer recordsProcessed) {
        this.recordsProcessed = recordsProcessed;
    }

    /**
     * Gets the number of records generated by the augmentation function as a result of its execution.
     * @return The number of records generated by the augmentation function as a result of its execution.
     */
    public Integer getRecordsGenerated() {
        return recordsGenerated;
    }

    /**
     * Sets the number of records generated by the augmentation function as a result of its execution.
     * @param recordsGenerated The number of records generated by the augmentation function as a result of its execution.
     */
    public void setRecordsGenerated(Integer recordsGenerated) {
        this.recordsGenerated = recordsGenerated;
    }

    /**
     * Gets the unique identifier for the execution of the augmentation function, allowing for better tracking and association
     * @return The unique identifier for the execution of the augmentation function, allowing for better tracking and association
     */
    public String getExecutionId() {
        return executionId;
    }

    /**
     * Sets the unique identifier for the execution of the augmentation function, allowing for better tracking and association
     * @param executionId The unique identifier for the execution of the augmentation function, allowing for better tracking and association
     */
    public void setExecutionId(String executionId) {
        this.executionId = executionId;
    }

    /**
     * Gets the unique identifier for the node on which the augmentation function was executed.
     * @return The unique identifier for the node on which the augmentation function was executed.
     */
    public String getNodeId() {
        return nodeId;
    }

    /**
     * Sets the unique identifier for the node on which the augmentation function was executed.
     * @param nodeId The unique identifier for the node on which the augmentation function was executed.
     */
    public void setNodeId(String nodeId) {
        this.nodeId = nodeId;
    }
}